export const lessons = [];
export function topic(
  moduleId,
  id,
  title,
  summary,
  mechanism,
  steps,
  pitfalls,
  question,
  scenario,
  scenarioAnswer,
  keywords,
  code = "",
  sourceIds = [],
) {
  const mod = modules.find((x) => x.id === moduleId);
  const sectionTexts = [
    summary,
    mechanism,
    ...steps.split("|"),
    ...pitfalls.split("|"),
  ];
  lessons.push({
    id,
    moduleId,
    title,
    summary,
    level: mod.priority === "P0" ? "核心" : "进阶",
    priority: mod.priority,
    estimatedMinutes: Math.max(8, Math.ceil(sectionTexts.join("").length / 65)),
    keywords: keywords.split(" "),
    sections: [
      { title: "先建立正确模型", content: mechanism },
      {
        title: "机制拆解与工程落地",
        content: steps
          .split("|")
          .map((s, i) => `${i + 1}. ${s}`)
          .join("\n"),
      },
      {
        title: "边界与常见误区",
        content: pitfalls
          .split("|")
          .map((s) => `- ${s}`)
          .join("\n"),
      },
    ],
    interview: {
      question,
      answer: `${summary}\n\n${mechanism}\n\n${steps
        .split("|")
        .map((s, i) => `${i + 1}. ${s}`)
        .join("\n")}\n\n边界：${pitfalls.split("|").join("；")}`,
      rubric: steps.split("|"),
      scenario,
      scenarioAnswer,
    },
    code,
    sourceIds: sourceIds.length
      ? sourceIds
      : {
          js: ["mdn-js", "ecma"],
          network: ["mdn-http"],
          css: ["mdn-css"],
          mini: ["wx-api", "wx-runtime"],
          framework: ["vue", "react"],
          engineering: ["vite", "webpack"],
          node: ["node-loop", "node-stream"],
          performance: ["vitals"],
          algorithm: ["mdn-js"],
          design: ["mdn-http"],
          project: [],
          ai: ["sse", "fetch"],
          architecture: [],
          strategy: [],
        }[moduleId],
    provenance: "editorial",
    updatedAt: "2026-10-21",
    order: lessons.filter((x) => x.moduleId === moduleId).length + 1,
  });
}
